const unique = [...new Set(Object.values(mods))].sort();
let out = `import type { BrandIconFn } from "reicon-brands/createIcon";\n\n`;
for (const m of unique) {
  out += `import ${m} from "reicon-brands/icons/${m}";\n`;
}
out += `\n/** Eager registry — tree-shaken to used icons only. */\n`;
out += `export const BRANDS: Record<string, BrandIconFn> = {\n`;
for (const [k, v] of Object.entries(mods)) {
  out += `  ${JSON.stringify(k)}: ${v} as BrandIconFn,\n`;
}
out += `};\n\n`;
out += `export function getBrand(key?: string): BrandIconFn | null {\n`;
out += `  if (!key) return null;\n  return BRANDS[key] ?? null;\n}\n`;

fs.writeFileSync("src/data/brands.ts", out);
