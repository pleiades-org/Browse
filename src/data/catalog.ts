/** Category display order for grouped All Apps */
export const CATEGORY_GROUP_ORDER: Array<
  Exclude<CategoryId, "all" | "popular" | "proton" | "ai">
> = [
  "development",
  "productivity",
  "media",
  "games",
  "security",
  "utilities",
  "internet",
];

export const DEFAULT_FILTERS: CatalogFilters = {
  popularOnly: false,
  niniteOnly: false,
  aiOnly: false,
  protonOnly: false,
  smallOnly: false,
  installableOnly: true,
};

export function isNinitePackage(pkg: AppPackage): boolean {
  return (
    pkg.tags?.includes("ninite") === true || NINITE_EXISTING_IDS.has(pkg.id)
  );
}

export function getPackage(id: string): AppPackage | undefined {
  return CATALOG.find((p) => p.id === id);
}

export function sortPackages(
  packages: AppPackage[],
  sort: SortKey,
): AppPackage[] {
  const list = [...packages];
  switch (sort) {
    case "name-desc":
      return list.sort((a, b) => b.name.localeCompare(a.name));
    case "size-asc":
      return list.sort((a, b) => a.sizeMb - b.sizeMb);
    case "size-desc":
      return list.sort((a, b) => b.sizeMb - a.sizeMb);
    case "popular":
      return list.sort((a, b) => {
        const pa = a.popular ? 1 : 0;
        const pb = b.popular ? 1 : 0;
        if (pb !== pa) return pb - pa;
        return a.name.localeCompare(b.name);
      });
    case "publisher":
      return list.sort(
        (a, b) =>
          a.publisher.localeCompare(b.publisher) ||
          a.name.localeCompare(b.name),
      );
    case "name-asc":
    default:
      return list.sort((a, b) => a.name.localeCompare(b.name));
  }
}

function packageSearchBlob(pkg: AppPackage): string {
  return [
    pkg.name,
    pkg.summary,
    pkg.publisher,
    pkg.category,
    pkg.brand ?? "",
    pkg.source,
    ...(pkg.tags ?? []),
  ].join(" ");
}

export function filterCatalog(
  category: CategoryId,
  query: string,
  filters: CatalogFilters = DEFAULT_FILTERS,
  sort: SortKey = "name-asc",
  platform?: Platform,
): AppPackage[] {
  // Bundles are a separate catalog — never mix into apps list
  if (category === "bundles") return [];

  const q = query.trim();
  const base = CATALOG.filter((pkg) => {
    if (platform && !isPackageOnPlatform(pkg, platform)) return false;
    if (platform && filters.installableOnly && !canInstallPackage(pkg, platform)) {
      return false;
    }
    if (category === "popular" && !pkg.popular) return false;
    if (category === "proton" && !pkg.tags?.includes("proton")) return false;
    if (category === "ai" && !pkg.tags?.includes("ai")) return false;
    if (
      category !== "all" &&
      category !== "popular" &&
      category !== "proton" &&
      category !== "ai" &&
      pkg.category !== category
    ) {
      return false;
    }
    if (filters.popularOnly && !pkg.popular) return false;
    if (filters.niniteOnly && !isNinitePackage(pkg)) return false;
    if (filters.aiOnly && !pkg.tags?.includes("ai")) return false;
    if (filters.protonOnly && !pkg.tags?.includes("proton")) return false;
    if (filters.smallOnly && pkg.sizeMb > 100) return false;
    return true;
  });

  if (!q) return sortPackages(base, sort);

  const scored = base
    .map((pkg) => {
      const nameScore = fuzzyScore(q, pkg.name) * 3;
      const blobScore = fuzzyScore(q, packageSearchBlob(pkg));
      return { pkg, score: Math.max(nameScore, blobScore) };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || a.pkg.name.localeCompare(b.pkg.name));

  if (scored.length > 0) return scored.map((x) => x.pkg);
  return [];
}

/** Smart empty-state: top fuzzy matches from entire catalog + category hints */
export function smartSearchHints(
  query: string,
  limit = 6,
): { packages: AppPackage[]; categories: Category[] } {
  const q = query.trim();
  if (!q) return { packages: [], categories: [] };

  const packages = CATALOG.map((pkg) => ({
    pkg,
    score: Math.max(
      fuzzyScore(q, pkg.name) * 3,
      fuzzyScore(q, packageSearchBlob(pkg)),
    ),
  }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.pkg);

  const categories = CATEGORIES.filter(
    (c) =>
      c.id !== "all" &&
      (fuzzyScore(q, c.label) > 0 || c.id.includes(q.toLowerCase())),
  ).slice(0, 4);

  return { packages, categories };
}

export function groupByCategory(
  packages: AppPackage[],
): Array<{ category: string; label: string; packages: AppPackage[] }> {
  const labelOf = (id: string) =>
    CATEGORIES.find((c) => c.id === id)?.label ?? id;

  const map = new Map<string, AppPackage[]>();
  for (const pkg of packages) {
    const list = map.get(pkg.category) ?? [];
    list.push(pkg);
    map.set(pkg.category, list);
  }

  const groups: Array<{
    category: string;
    label: string;
    packages: AppPackage[];
  }> = [];

  // Featured Popular strip at top — same apps still appear under their category
  const popular = packages.filter((p) => p.popular);
  if (popular.length) {
    groups.push({
      category: "popular",
      label: "Popular",
      packages: popular,
    });
  }

  for (const id of CATEGORY_GROUP_ORDER) {
    const pkgs = map.get(id);
    if (pkgs?.length) {
      groups.push({ category: id, label: labelOf(id), packages: pkgs });
      map.delete(id);
    }
  }
  // Any leftover categories
  for (const [id, pkgs] of map) {
    if (pkgs.length) {
      groups.push({ category: id, label: labelOf(id), packages: pkgs });
    }
  }
  return groups;
}
